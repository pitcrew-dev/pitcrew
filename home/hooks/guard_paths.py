#!/usr/bin/env python
"""PreToolUse guard for Write/Edit.

Enforces the parts of company/standards/code-ownership.md that must not depend
on an agent remembering them: generated output, vendored dependencies, secrets,
and third-party code are never hand-edited.

Contract: exit 2 blocks the tool call and returns stderr to the model.
Any internal error exits 0 — this guard fails OPEN so a bug here can never
stop legitimate work.
"""
import json
import re
import sys

# (regex over the forward-slashed lowercase path, reason shown to the agent)
DENY = [
    (r"(^|/)vendor/",
     "vendor/ is installed by Composer. Never hand-edit it — the change is destroyed on the next install. Fix the source, or raise a dependency change with the PM."),
    (r"(^|/)node_modules/",
     "node_modules/ is installed by npm. Never hand-edit it. Fix the source or the dependency."),
    (r"(^|/)public/build/",
     "public/build/ is compiled output. If the built CSS or JS is wrong, the source in resources/ is wrong — fix that instead."),
    (r"(^|/)\.env(\.|$)",
     ".env holds secrets and is never committed or written by an agent. Add the key to .env.example and tell the user which value to set themselves."),
    (r"(^|/)wp-admin/|(^|/)wp-includes/|(^|/)wp-settings\.php$|(^|/)wp-load\.php$",
     "WordPress core is never modified — the next update overwrites it. Extend via a child theme, a custom plugin, or hooks (stack-profiles.md, Profile D)."),
    (r"(^|/)\.git/",
     "Never write into .git/ directly. Use git commands."),
    (r"\.min\.(js|css)$",
     "Minified assets are generated. Edit the source file instead."),
    (r"(^|/)(composer|package)-?lock\.(json|lock)$|(^|/)composer\.lock$",
     "Lock files are generated by the package manager. Run the install/update command instead of editing them."),
]


def main() -> int:
    raw = sys.stdin.read()
    payload = json.loads(raw)

    tool_input = payload.get("tool_input") or {}
    path = tool_input.get("file_path") or tool_input.get("notebook_path") or ""
    if not path:
        return 0

    normalized = path.replace("\\", "/").lower()

    # .env.example is a committed template, not a secret — always allowed.
    if re.search(r"\.env\.example$", normalized):
        return 0

    for pattern, reason in DENY:
        if re.search(pattern, normalized):
            sys.stderr.write("BLOCKED by code-ownership guard: %s\n\n%s\n" % (path, reason))
            return 2

    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except Exception:
        # Fail open. A broken guard must never block real work.
        sys.exit(0)
