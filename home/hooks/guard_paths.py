#!/usr/bin/env python3
"""PreToolUse guard for Write/Edit/NotebookEdit.

Blocks writes an agent must never make, whatever it has been told:
installed dependencies, generated output, secrets, private keys, third-party
core code and lock files.

Contract: exit 2 blocks the tool call and returns the reason to the agent.
Fails OPEN on any internal error: a bug here must never block real work.
"""
import json
import re
import sys

# Committed templates with no real secrets. Always writable.
ALLOWED = re.compile(r"(^|/)\.env\.(example|dist|sample|template)$")

# (regex over the forward-slashed, lower-cased path, reason shown to the agent)
DENY = [
    (r"(^|/)vendor/",
     "vendor/ is installed by Composer. A hand edit is destroyed on the next install. "
     "Fix the source, or raise a dependency change with the PM."),
    (r"(^|/)node_modules/",
     "node_modules/ is installed by npm. Never hand-edit it. Fix the source or the dependency."),
    (r"(^|/)public/(build|hot)(/|$)",
     "public/build/ is compiled output. If the built CSS or JS is wrong, fix the source instead."),
    (r"(^|/)\.env(\.[^/]*)?$",
     ".env files hold secrets and are never written by an agent. Add the key to .env.example "
     "and tell the user which value to set."),
    (r"(^|/)wp-config\.php$",
     "wp-config.php holds the database password and security keys. Never written by an agent: "
     "tell the user exactly which line to change and why."),
    (r"(^|/)(wp-admin|wp-includes)/|(^|/)wp-(settings|load|login|cron|blog-header|links-opml|mail"
     r"|signup|trackback|activate|comments-post)\.php$",
     "WordPress core is never modified; the next update overwrites it. Extend it with a child "
     "theme, a custom plugin or hooks."),
    (r"(^|/)\.git/",
     "Never write into .git/ directly. Use git commands."),
    (r"\.min\.(js|css)$",
     "Minified assets are generated. Edit the source file instead."),
    (r"(^|/)(composer\.lock|package-lock\.json|yarn\.lock|pnpm-lock\.yaml|bun\.lockb?)$",
     "Lock files are generated by the package manager. Run the install/update command instead."),
    (r"\.(pem|key|p12|pfx|jks|keystore)$|(^|/)id_(rsa|dsa|ecdsa|ed25519)$|(^|/)\.ssh/",
     "Private keys and certificates are never written by an agent. Tell the user what is needed "
     "and let them create it."),
]


def main():
    payload = json.loads(sys.stdin.read() or "{}")
    tool_input = payload.get("tool_input") or {}
    path = tool_input.get("file_path") or tool_input.get("notebook_path") or ""
    if not path:
        return 0

    normalized = path.replace("\\", "/").lower()
    if ALLOWED.search(normalized):
        return 0

    for pattern, reason in DENY:
        if re.search(pattern, normalized):
            sys.stderr.write("BLOCKED by the protected-files guard: %s\n\n%s\n" % (path, reason))
            return 2
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except Exception:
        sys.exit(0)
